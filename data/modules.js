// ── HELPER FUNKCIJE ──

function getModuleById(id) {
  return MODULES.find(m => m.id === id) || null;
}

function getModulesByRarity(rarity) {
  return MODULES.filter(m => m.rarity === rarity);
}

function getModulesByCategory(category) {
  return MODULES.filter(m => m.category === category);
}

function getModulesByVariant(variant) {
  return MODULES.filter(m => m.variant === variant);
}

function canShipUseModule(shipClass, moduleId) {
  const mod = getModuleById(moduleId);
  if (!mod) return false;
  if (mod.who === 'Samo Flagship') return shipClass === 'special';
  return true;
}

