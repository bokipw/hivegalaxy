function getEngineById(id) {
  return ENGINES.find(e => e.id === id) || null;
}

function getEnginesByRarity(rarity) {
  return ENGINES.filter(e => e.rarity === rarity);
}

function getEnginesByVariant(variant) {
  return ENGINES.filter(e => e.variant === variant);
}

function getBestEngineForClass(shipClass) {
  const recommendations = {
    scout:      'eng_stealth_III',
    fighter:    'eng_sprint_III',
    cruiser:    'eng_sentinel_III',
    battleship: 'eng_heavy_III',
    carrier:    'eng_heavy_III',
    special:    'eng_hyperdrive_III',
  };
  return getEngineById(recommendations[shipClass]);
}

