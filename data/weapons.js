// ── HELPER FUNKCIJE ──

function getWeaponById(id) {
  return WEAPONS.find(w => w.id === id) || null;
}

function getWeaponsBySubtype(subtype) {
  return WEAPONS.filter(w => w.subtype === subtype);
}

function getWeaponsByDamageType(dmgType) {
  return WEAPONS.filter(w => w.dmgType === dmgType);
}

function getWeaponsByRarity(rarity) {
  return WEAPONS.filter(w => w.rarity === rarity);
}

function canShipUseWeapon(shipClass, weaponId) {
  const weapon = getWeaponById(weaponId);
  if (!weapon) return false;
  if (weapon.subtype === 'FighterBay') {
    return shipClass === 'carrier' || shipClass === 'special';
  }
  return true;
}

